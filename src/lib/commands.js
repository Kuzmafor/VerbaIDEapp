export const SLASH_COMMANDS = [
  { id: 'fix', title: 'Исправить ошибку', hint: 'Найти причину и внести безопасную правку' },
  { id: 'review', title: 'Провести ревью', hint: 'Ошибки, безопасность и регрессии' },
  { id: 'test', title: 'Создать тесты', hint: 'Покрыть изменение проверками' },
  { id: 'explain', title: 'Объяснить код', hint: 'Разобрать выделение или указанный файл' },
  { id: 'commit', title: 'Подготовить коммит', hint: 'Проверить изменения и написать сообщение' },
  { id: 'search', title: 'Найти информацию', hint: 'Поиск по проекту и, если доступно, в интернете' },
]

export function expandSlashCommand(value, { selection = '', webAvailable = false } = {}) {
  const match = String(value || '').trim().match(/^\/(fix|review|test|explain|commit|search)(?:\s+([\s\S]*))?$/i)
  if (!match) return null
  const id = match[1].toLowerCase()
  const extra = (match[2] || '').trim()
  const suffix = extra ? `\n\nДополнение пользователя:\n${extra}` : ''
  const prompts = {
    fix: 'Найди причину описанной ошибки в проекте, прочитай связанные файлы, внеси минимальную безопасную правку и объясни, как проверить результат.',
    review: 'Проведи строгое ревью текущего проекта или указанных файлов. Найди реальные ошибки, уязвимости, регрессии и проблемы производительности. Сначала покажи наиболее важное.',
    test: 'Изучи текущую реализацию и создай или обнови подходящие автоматические тесты. Учитывай существующий стек и стиль тестов проекта.',
    explain: selection
      ? `Объясни выделенный фрагмент кода простым языком: что он делает, как устроен и какие есть риски.\n\n<selected_code>\n${selection}\n</selected_code>`
      : 'Объясни указанный код или файл: назначение, поток данных, важные зависимости и потенциальные риски. Если контекста недостаточно, найди связанный код в проекте.',
    commit: 'Проанализируй текущие изменения проекта, кратко перечисли их и подготовь точное commit message в общепринятом формате. Не выдумывай изменения, которых нет.',
    search: `Найди информацию по запросу. Сначала используй semantic_search и точный поиск по проекту.${webAvailable ? ' Также используй доступный провайдеру поиск в интернете и укажи источники.' : ' Интернет-поиск у выбранного провайдера не подтверждён — явно отдели знания модели от найденного в проекте.'}`,
  }
  return { id, content: prompts[id] + suffix }
}
